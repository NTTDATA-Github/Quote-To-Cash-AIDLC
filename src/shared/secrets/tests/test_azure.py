from __future__ import annotations

import pytest

from src.shared.secrets.azure import KeyVaultSecretStore
from src.shared.secrets.store import SecretNotFound


class _FakeSecret:
    def __init__(self, value: str) -> None:
        self.value = value


class _FakeClient:
    def __init__(self) -> None:
        self.secrets: dict[str, str] = {}
        self.requested_names: list[str] = []

    def get_secret(self, name: str) -> _FakeSecret:
        self.requested_names.append(name)
        if name not in self.secrets:
            raise KeyError(name)
        return _FakeSecret(self.secrets[name])

    def set_secret(self, name: str, value: str) -> None:
        self.requested_names.append(name)
        self.secrets[name] = value


def test_slashes_and_underscores_in_secret_ref_are_translated_to_a_legal_vault_name() -> None:
    """Key Vault secret names forbid "/" and "_", but `secret_ref`s like
    "erp-connection/<id>" (generated by cloud-agnostic application code) always contain
    a "/", and `<id>` (from `generate_id()`) always contains a "_"."""
    client = _FakeClient()
    store = KeyVaultSecretStore("https://vault.example/", client=client)

    store.put_secret("erp-connection/conn_123", "s3cr3t")

    assert client.requested_names == ["erp-connection--conn-123"]
    assert store.get_secret("erp-connection/conn_123") == "s3cr3t"


def test_put_then_get_round_trips() -> None:
    client = _FakeClient()
    store = KeyVaultSecretStore("https://vault.example/", client=client)

    store.put_secret("webhook-endpoint/ep_1", "whsec")

    assert store.get_secret("webhook-endpoint/ep_1") == "whsec"


def test_missing_secret_raises_secret_not_found() -> None:
    client = _FakeClient()
    store = KeyVaultSecretStore("https://vault.example/", client=client)

    with pytest.raises(SecretNotFound):
        store.get_secret("erp-connection/does-not-exist")


def test_put_overwrites_an_existing_secret_in_one_call() -> None:
    """`set_secret` creates-or-overwrites, so there is no separate create/update path to
    exercise here."""
    client = _FakeClient()
    store = KeyVaultSecretStore("https://vault.example/", client=client)

    store.put_secret("erp-connection/conn_123", "first")
    store.put_secret("erp-connection/conn_123", "second")

    assert store.get_secret("erp-connection/conn_123") == "second"
