"""Azure Key Vault implementation of the `SecretStore` port (ADR-0023).

Deliberately in its own module (not `store.py`), same reason as `aws.py`: it imports the
`azure-*` SDKs, and keeping it out of the port module means a domain module can depend on
`SecretStore` without transitively pulling in a cloud SDK — the "domain is framework-free"
import-linter contract. Only the composition root (api/worker layer) imports this.
"""

from __future__ import annotations

from typing import Any

from .store import SecretNotFound


def _vault_name(secret_ref: str) -> str:
    """Key Vault secret names allow only `[0-9A-Za-z-]` — no `/` or `_`. `secret_ref`
    values are generated by cloud-agnostic application code (e.g. `erp-connection/<id>`,
    `webhook-endpoint/<id>` — see `connections/application/service.py`) whose `<id>` comes
    from `generate_id()`, always `<prefix>_<hex>`, so the underscore needs translating too.
    Deterministic in both directions `get_secret` and `put_secret` go through, so nothing
    ever needs to reverse it."""
    return secret_ref.replace("/", "--").replace("_", "-")


class KeyVaultSecretStore:
    """Resolves a `secret_ref` against Azure Key Vault via the `azure-keyvault-secrets` SDK.

    Auth: `DefaultAzureCredential` by default (picks up `az login` locally, the Container
    App's managed identity in Azure); pass `managed_identity_client_id` to pin a specific
    user-assigned identity when more than one exists on the host (api/worker/odoo each
    have their own — see `infra/azure/modules/iam`).
    """

    def __init__(
        self,
        vault_uri: str,
        client: Any | None = None,
        credential: Any | None = None,
        managed_identity_client_id: str | None = None,
    ) -> None:
        if client is None:
            from azure.identity import DefaultAzureCredential, ManagedIdentityCredential
            from azure.keyvault.secrets import SecretClient

            if credential is None:
                credential = (
                    ManagedIdentityCredential(client_id=managed_identity_client_id)
                    if managed_identity_client_id
                    else DefaultAzureCredential()
                )
            client = SecretClient(vault_url=vault_uri, credential=credential)
        self._client = client

    def get_secret(self, secret_ref: str) -> str:
        try:
            secret = self._client.get_secret(_vault_name(secret_ref))
        except Exception as exc:
            raise SecretNotFound(secret_ref) from exc
        return str(secret.value)

    def put_secret(self, secret_ref: str, value: str) -> None:
        # `set_secret` creates-or-overwrites in one call.
        self._client.set_secret(_vault_name(secret_ref), value)
